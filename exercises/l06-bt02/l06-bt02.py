import math as m
import random as rd

# Tính căn bậc hai của 25
print(f"Tính căn bậc hai của 25: {m.sqrt(25)}")

# Tính cos của 60 độ (chuyển sang radian)
print(f"Tính cos của 60 độ (radian): {m.cos(m.radians(60))}")

# Sinh một số ngẫu nhiên từ 1 đến 100
print(f"Sinh một số ngẫu nhiên từ 1 đến 100: {rd.randint(1, 100)}")
